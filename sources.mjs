// Catégories et sources de Vigie. Pour ajouter une source : une ligne dans `sources`.
// weight : importance (source primaire > 1). kind : article | video | deal | social.
// noLead : images souvent peu lisibles (captures d'écran, code), jamais en grande une.
const rss = (name, url, opts = {}) => ({ name, url, ...opts });
const reddit = (sub, t = 'day', opts = {}) => ({ name: `r/${sub}`, url: `https://www.reddit.com/r/${sub}/top/.rss?t=${t}`, kind: 'social', weight: 0.8, ...opts });
const yt = (name, id) => ({ name, url: `https://www.youtube.com/feeds/videos.xml?channel_id=${id}`, kind: 'video' });
const hn = (q, points = 50) => ({ name: 'Hacker News', url: `https://hnrss.org/newest?q=${encodeURIComponent(q)}&points=${points}`, kind: 'social', weight: 0.9 });
const bsky = (name, handle) => ({ name, url: `https://bsky.app/profile/${handle}/rss`, kind: 'social' });
const dealabs = (name, group) => ({ name: `Dealabs · ${name}`, url: `https://www.dealabs.com/rss/groupe/${group}`, kind: 'deal' });

